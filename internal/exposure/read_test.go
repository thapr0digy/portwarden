func readFixture(t *testing.T, name string) []byte {
	t.Helper()
	data, err := os.ReadFile("testdata/" + name)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

var vm = netip.MustParseAddr("192.168.5.15")

func vmEval(fw *Firewall, proto string, port uint16) firewall.Result {
	env := firewall.Env{
		IsLocal: func(a netip.Addr) bool { return a == vm || a == netip.MustParseAddr("172.17.0.1") || a.IsLoopback() },
		Route: func(a netip.Addr) (string, bool) {
			if netip.MustParsePrefix("172.17.0.0/16").Contains(a) {
				return "docker0", true
			}
			return "eth0", true
		},
	}
	return fw.Rules.Evaluate(firewall.Packet{Family: firewall.FamilyIP, Proto: proto, DAddr: vm, DPort: port, IIf: "eth0"}, env)
}

func TestMergeReplacesXTTablesWithIptablesSave(t *testing.T) {
	fw, err := Merge(MergeInput{
		NFT:  readFixture(t, "docker-iptables-nft.json"),
		IPT4: readFixture(t, "docker-iptables-nft.v4.txt"),
		IPT6: readFixture(t, "docker-iptables-nft.v6.txt"),
	})
	if err != nil {
		t.Fatal(err)
	}
	if fw.Sources != "nft+iptables(nf_tables)" || fw.Legacy {
		t.Fatalf("sources %q legacy %v", fw.Sources, fw.Legacy)
	}
	for _, c := range fw.Rules.Chains {
		if c.Origin == "nft" {
			t.Errorf("nft chain %s kept although iptables-save printed its table", c.Where())
		}
	}
	r := vmEval(fw, "tcp", 18080)
	if r.Decision() != firewall.Open || r.Outcomes[0].DAddr != netip.MustParseAddr("172.17.0.2") {
		t.Fatalf("18080: %+v", r)
	}
}

func TestMergeKeepsNativeTables(t *testing.T) {
	fw, err := Merge(MergeInput{
		NFT:  readFixture(t, "docker-nftables.json"),
		IPT4: readFixture(t, "docker-nftables.v4.txt"),
		IPT6: readFixture(t, "docker-nftables.v6.txt"),
	})
	if err != nil {
		t.Fatal(err)
	}
	native := 0
	for _, c := range fw.Rules.Chains {
		if c.Origin == "nft" {
			if c.Table != "docker-bridges" {
				t.Errorf("nft chain %s should come from iptables-save", c.Where())
			}
			native++
		}
	}
	if native == 0 {
		t.Fatal("docker-bridges chains dropped")
	}
	r := vmEval(fw, "tcp", 18080)
	if r.Decision() != firewall.Open || r.Outcomes[0].Origin != "nft" {
		t.Fatalf("18080: %+v", r)
	}
}

func TestMergeUfw(t *testing.T) {
	fw, err := Merge(MergeInput{
		NFT:  readFixture(t, "ufw-docker-nft.json"),
		IPT4: readFixture(t, "ufw-docker.v4.txt"),
		IPT6: readFixture(t, "ufw-docker.v6.txt"),
	})
	if err != nil {
		t.Fatal(err)
	}
	for port, want := range map[uint16]firewall.Decision{22: firewall.Open, 8443: firewall.Open, 80: firewall.Closed, 18080: firewall.Open} {
		if got := vmEval(fw, "tcp", port).Decision(); got != want {
			t.Errorf("tcp/%d: %v, want %v", port, got, want)
		}
	}
}

func TestMergeLegacyBothApply(t *testing.T) {
	legacy := "# Generated by iptables-save v1.8.7 (legacy) on x\n*filter\n:INPUT DROP [0:0]\n-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT\nCOMMIT\n"
	native := `{"nftables":[{"table":{"family":"inet","name":"f"}},
	 {"chain":{"family":"inet","table":"f","name":"in","type":"filter","hook":"input","prio":0,"policy":"accept"}},
	 {"rule":{"family":"inet","table":"f","chain":"in","expr":[{"match":{"op":"==","left":{"payload":{"protocol":"tcp","field":"dport"}},"right":22}},{"drop":null}]}}]}`
	fw, err := Merge(MergeInput{NFT: []byte(native), IPT4: []byte(legacy), IPT6Err: fmt.Errorf("ip6tables-save: %w", ErrToolMissing)})
	if err != nil {
		t.Fatal(err)
	}
	if !fw.Legacy || fw.Sources != "nft+iptables-legacy" {
		t.Fatalf("legacy %v sources %q", fw.Legacy, fw.Sources)
	}
	if got := vmEval(fw, "tcp", 22).Decision(); got != firewall.Closed {
		t.Fatalf("the native drop must still apply: %v", got)
	}
}

func TestMergeFailures(t *testing.T) {
	_, err := Merge(MergeInput{NFTErr: errors.New("nft: Operation not permitted"), IPT4Err: errors.New("iptables-save: Permission denied"), IPT6Err: errors.New("x")})
	if err == nil || !strings.Contains(err.Error(), "Operation not permitted") {
		t.Fatalf("got %v", err)
	}
	fw, err := Merge(MergeInput{NFTErr: fmt.Errorf("nft: %w", ErrToolMissing), IPT4: readFixture(t, "ufw-docker.v4.txt"), IPT6Err: errors.New("boom")})
	if err != nil {
		t.Fatal(err)
	}
	if len(fw.Notes) != 2 || fw.Sources != "iptables(nf_tables)" {
		t.Fatalf("notes %v sources %q", fw.Notes, fw.Sources)
	}
}

func TestFingerprintIgnoresCounters(t *testing.T) {
	a := readFixture(t, "docker-iptables-nft.v4.txt")
	b := []byte(strings.ReplaceAll(strings.ReplaceAll(string(a), "[0:0]", "[7:999]"), "Mon Nov", "Tue Nov"))
	fa, err1 := Merge(MergeInput{IPT4: a})
	fb, err2 := Merge(MergeInput{IPT4: b})
	if err1 != nil || err2 != nil {
		t.Fatal(err1, err2)
	}
	if fa.Fingerprint != fb.Fingerprint {
		t.Fatal("counters changed the fingerprint")
	}
	fc, _ := Merge(MergeInput{IPT4: readFixture(t, "ufw-docker.v4.txt")})
	if fc.Fingerprint == fa.Fingerprint {
		t.Fatal("different rules, same fingerprint")
	}
}

func TestReadFirewallRunsLegacyWhenWarned(t *testing.T) {
	var ran []string
	run := func(_ context.Context, name string, _ ...string) ([]byte, error) {
		ran = append(ran, name)
		switch name {
		case "iptables-save":
			return []byte("# Warning: iptables-legacy tables present, use iptables-legacy-save to see them\n"), nil
		case "iptables-legacy-save":
			return []byte("# Generated by iptables-save v1.8.10 (legacy) on x\n*filter\n:INPUT DROP [0:0]\nCOMMIT\n"), nil
		}
		return nil, fmt.Errorf("%s: %w", name, ErrToolMissing)
	}
	fw, err := ReadFirewall(context.Background(), run)
	if err != nil {
		t.Fatal(err)
	}
	if !fw.Legacy || !strings.Contains(strings.Join(ran, ","), "iptables-legacy-save") {
		t.Fatalf("legacy %v ran %v", fw.Legacy, ran)
	}
	if got := vmEval(fw, "tcp", 1).Decision(); got != firewall.Closed {
		t.Fatalf("legacy drop policy: %v", got)
	}
}

func TestExecRunner(t *testing.T) {
	if _, err := ExecRunner(context.Background(), "portwarden-no-such-tool"); !errors.Is(err, ErrToolMissing) {
		t.Fatalf("missing tool: %v", err)
	}
	out, err := ExecRunner(context.Background(), "sh", "-c", "echo hi")
	if err != nil || string(out) != "hi\n" {
		t.Fatalf("out %q err %v", out, err)
	}
	if _, err := ExecRunner(context.Background(), "sh", "-c", "echo nope >&2; exit 3"); err == nil || !strings.Contains(err.Error(), "nope") {
		t.Fatalf("failure: %v", err)
	}
}
