// Package iptables reads `iptables-save` / `ip6tables-save` output into the firewall
// model.
//
// The core options (-p -s -d -i -o -j -g) and the match modules that decide an inbound
// packet's fate (tcp, udp, multiport, conntrack, state, addrtype, mark, iprange,
// pkttype, comment, nfacct) are understood. Any other module, and any option the parser
// does not know, makes the rule's match "maybe" rather than a guess. Targets are
// ACCEPT, DROP, REJECT, RETURN, QUEUE/NFQUEUE, DNAT, REDIRECT, MARK, user chains (jump)
// and -g (goto); any other target (LOG, MASQUERADE, SNAT, CT, …) does not end the rule's
// effect on the verdict and is skipped.
package iptables

import (
	"bufio"
	"bytes"
	"fmt"
	"math"
	"net/netip"
	"strconv"
	"strings"

	"github.com/thapr0digy/portwarden/internal/exposure/firewall"
)

// Ruleset is one parsed iptables-save (or ip6tables-save) dump.
type Ruleset struct {
	// Backend is "nf_tables" or "legacy", from the dump's header; "" when it has none.
	Backend string
	// Tables lists the tables the dump printed in full.
	Tables []string
	Chains []*firewall.Chain
	// LegacyPresent: iptables-nft warned that iptables-legacy tables exist too.
	LegacyPresent bool
}

// builtin is where iptables registers a table's built-in chains.
type builtin struct {
	hook firewall.Hook
	typ  firewall.ChainType
	prio int
}

var builtins = map[string]map[string]builtin{
	"raw": {
		"PREROUTING": {firewall.HookPrerouting, firewall.TypeFilter, -300},
		"OUTPUT":     {firewall.HookOutput, firewall.TypeFilter, -300},
	},
	"mangle": {
		"PREROUTING":  {firewall.HookPrerouting, firewall.TypeFilter, -150},
		"INPUT":       {firewall.HookInput, firewall.TypeFilter, -150},
		"FORWARD":     {firewall.HookForward, firewall.TypeFilter, -150},
		"OUTPUT":      {firewall.HookOutput, firewall.TypeRoute, -150},
		"POSTROUTING": {firewall.HookPostrouting, firewall.TypeFilter, -150},
	},
	"nat": {
		"PREROUTING":  {firewall.HookPrerouting, firewall.TypeNAT, -100},
		"INPUT":       {firewall.HookInput, firewall.TypeNAT, 100},
		"OUTPUT":      {firewall.HookOutput, firewall.TypeNAT, -100},
		"POSTROUTING": {firewall.HookPostrouting, firewall.TypeNAT, 100},
	},
	"filter": {
		"INPUT":   {firewall.HookInput, firewall.TypeFilter, 0},
		"FORWARD": {firewall.HookForward, firewall.TypeFilter, 0},
		"OUTPUT":  {firewall.HookOutput, firewall.TypeFilter, 0},
	},
	"security": {
		"INPUT":   {firewall.HookInput, firewall.TypeFilter, 50},
		"FORWARD": {firewall.HookForward, firewall.TypeFilter, 50},
		"OUTPUT":  {firewall.HookOutput, firewall.TypeFilter, 50},
	},
}

// Parse reads a dump whose rules are of family fam (FamilyIP for iptables-save,
// FamilyIP6 for ip6tables-save).
func Parse(data []byte, fam firewall.Family) (*Ruleset, error) {
	rs := &Ruleset{}
	var table string
	var tableChains map[string]*firewall.Chain
	var pending []*firewall.Chain
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(make([]byte, 64*1024), 16<<20)
	lineNo := 0
	for sc.Scan() {
		lineNo++
		line := strings.TrimSpace(sc.Text())
		switch {
		case line == "":
		case strings.HasPrefix(line, "#"):
			if strings.HasPrefix(line, "# Generated by ") {
				switch {
				case strings.Contains(line, "(nf_tables)"):
					rs.Backend = "nf_tables"
				case strings.Contains(line, "(legacy)"):
					rs.Backend = "legacy"
				}
			}
			if strings.Contains(line, "iptables-legacy tables present") {
				rs.LegacyPresent = true
			}
		case strings.HasPrefix(line, "*"):
			table = line[1:]
			tableChains = make(map[string]*firewall.Chain)
			pending = nil
		case strings.HasPrefix(line, ":"):
			if table == "" {
				return nil, fmt.Errorf("iptables: line %d: chain outside a table", lineNo)
			}
			fields := strings.Fields(line[1:])
			if len(fields) < 2 {
				return nil, fmt.Errorf("iptables: line %d: bad chain line", lineNo)
			}
			c := &firewall.Chain{Origin: "iptables", Family: fam, Table: table, Name: fields[0], Policy: firewall.VerdictAccept}
			if b, ok := builtins[table][fields[0]]; ok {
				c.Hook, c.Type, c.Prio = b.hook, b.typ, b.prio
				if fields[1] == "DROP" {
					c.Policy = firewall.VerdictDrop
				}
			}
			tableChains[c.Name] = c
			pending = append(pending, c)
		case strings.HasPrefix(line, "-A "):
			if table == "" {
				return nil, fmt.Errorf("iptables: line %d: rule outside a table", lineNo)
			}
			args, err := split(line[3:])
			if err != nil {
				return nil, fmt.Errorf("iptables: line %d: %w", lineNo, err)
			}
			if len(args) == 0 {
				return nil, fmt.Errorf("iptables: line %d: rule without a chain", lineNo)
			}
			c := tableChains[args[0]]
			if c == nil {
				return nil, fmt.Errorf("iptables: line %d: rule for undeclared chain %s", lineNo, args[0])
			}
			r, err := parseRule(args[1:], fam, tableChains)
			if err != nil {
				return nil, fmt.Errorf("iptables: line %d: %w", lineNo, err)
			}
			c.Rules = append(c.Rules, r)
		case line == "COMMIT":
			if table == "" {
				return nil, fmt.Errorf("iptables: line %d: COMMIT outside a table", lineNo)
			}
			rs.Tables = append(rs.Tables, table)
			rs.Chains = append(rs.Chains, pending...)
			table, tableChains, pending = "", nil, nil
		default:
			return nil, fmt.Errorf("iptables: line %d: unexpected %q", lineNo, line)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("iptables: %w", err)
	}
	if table != "" {
		return nil, fmt.Errorf("iptables: table %s has no COMMIT (truncated dump)", table)
	}
	return rs, nil
}

// split tokenises a rule line as iptables-save quotes it: double quotes, with
// backslash escapes inside.
func split(s string) ([]string, error) {
	var out []string
	var cur strings.Builder
	inQuote, have := false, false
	for i := 0; i < len(s); i++ {
		ch := s[i]
		switch {
		case inQuote && ch == '\\' && i+1 < len(s):
			i++
			cur.WriteByte(s[i])
		case ch == '"':
			inQuote = !inQuote
			have = true
		case !inQuote && (ch == ' ' || ch == '\t'):
			if have {
				out = append(out, cur.String())
				cur.Reset()
				have = false
			}
		default:
			cur.WriteByte(ch)
			have = true
		}
	}
	if inQuote {
		return nil, fmt.Errorf("unterminated quote")
	}
	if have {
		out = append(out, cur.String())
	}
	return out, nil
}

// ruleParser walks one rule's arguments.
type ruleParser struct {
	args   []string
	i      int
	fam    firewall.Family
	proto  string // from -p, qualifies --dport/--sport
	module string // the last -m
	chains map[string]*firewall.Chain
	rule   firewall.Rule
	recent *recentMatch
}

// recentMatch is a -m recent match being read.
type recentMatch struct {
	action string
	neg    bool
	rdest  bool
}

// flushRecent decides a pending -m recent: a fresh outside source has no entry in a
// source-keyed list, so --set/--remove hold and --rcheck/--update do not. A list keyed
// on the destination (--rdest) may already hold the host's address: maybe.
func (p *ruleParser) flushRecent() {
	r := p.recent
	p.recent = nil
	switch {
	case r == nil:
	case r.rdest:
		p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "recent --rdest"})
	case (r.action == "--set" || r.action == "--remove") == r.neg:
		p.add(never())
	}
}

// never is a match nothing satisfies (an empty protocol set).
func never() firewall.Match { return firewall.Match{Field: firewall.FieldL4Proto} }

func parseRule(args []string, fam firewall.Family, chains map[string]*firewall.Chain) (firewall.Rule, error) {
	p := &ruleParser{args: args, fam: fam, chains: chains}
	var target []firewall.Expr
	for p.i < len(p.args) {
		neg := false
		if p.args[p.i] == "!" {
			neg = true
			p.i++
			if p.i >= len(p.args) {
				return p.rule, fmt.Errorf("dangling !")
			}
		}
		opt := p.args[p.i]
		p.i++
		switch opt {
		case "-p", "--protocol":
			v, err := p.value(opt)
			if err != nil {
				return p.rule, err
			}
			p.proto = strings.ToLower(v)
			if p.proto == "all" {
				if neg {
					p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "! -p all"})
				}
				continue
			}
			p.add(firewall.Match{Field: firewall.FieldL4Proto, Op: op(neg), Names: []string{protoName(p.proto)}})
		case "-s", "--source", "-d", "--destination":
			v, err := p.value(opt)
			if err != nil {
				return p.rule, err
			}
			field := firewall.FieldSAddr
			if opt == "-d" || opt == "--destination" {
				field = firewall.FieldDAddr
			}
			pfx, err := prefixes(v)
			if err != nil {
				return p.rule, err
			}
			p.add(firewall.Match{Field: field, Op: op(neg), Family: p.fam, Pfx: pfx})
		case "-i", "--in-interface", "-o", "--out-interface":
			v, err := p.value(opt)
			if err != nil {
				return p.rule, err
			}
			field := firewall.FieldIIf
			if opt == "-o" || opt == "--out-interface" {
				field = firewall.FieldOIf
			}
			// iptables' wildcard is a trailing '+'.
			if strings.HasSuffix(v, "+") {
				v = strings.TrimSuffix(v, "+") + "*"
			}
			p.add(firewall.Match{Field: field, Op: op(neg), Names: []string{v}})
		case "-f", "--fragment":
			p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "fragment"})
		case "-m", "--match":
			p.flushRecent()
			v, err := p.value(opt)
			if err != nil {
				return p.rule, err
			}
			p.module = v
			if headerModules[v] {
				// Matches on an extension header or IPsec header a plain new TCP or UDP
				// packet does not carry: they never match it, inverted or not.
				p.add(never())
				continue
			}
			if !knownModules[v] {
				p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "-m " + v})
			}
			if v == "limit" {
				// The first packet of a new connection is under any rate.
				p.add(firewall.Match{Field: firewall.FieldAlways, Note: "rate-limited"})
			}
		case "-j", "--jump", "-g", "--goto":
			p.flushRecent()
			v, err := p.value(opt)
			if err != nil {
				return p.rule, err
			}
			t, err := p.target(v, opt == "-g" || opt == "--goto")
			if err != nil {
				return p.rule, err
			}
			target = t
		case "-c", "--set-counters":
			p.i += 2
		default:
			if err := p.moduleOption(opt, neg); err != nil {
				return p.rule, err
			}
		}
	}
	p.flushRecent()
	if target == nil {
		// No verdict (LOG and the like): a rate limit here decides nothing worth noting.
		for i, x := range p.rule.Exprs {
			if m, ok := x.(firewall.Match); ok && m.Note != "" {
				m.Note = ""
				p.rule.Exprs[i] = m
			}
		}
	}
	p.rule.Exprs = append(p.rule.Exprs, target...)
	return p.rule, nil
}

var knownModules = map[string]bool{
	"tcp": true, "udp": true, "multiport": true, "conntrack": true, "state": true,
	"addrtype": true, "mark": true, "comment": true, "iprange": true, "pkttype": true,
	"nfacct": true, "icmp": true, "icmp6": true, "icmpv6": true,
	"recent": true, "limit": true, "hashlimit": true, "connlimit": true, "set": true,
}

var headerModules = map[string]bool{"rt": true, "frag": true, "hbh": true, "dst": true, "ah": true, "esp": true, "mh": true}

func op(neg bool) firewall.Op {
	if neg {
		return firewall.OpNe
	}
	return firewall.OpEq
}

func (p *ruleParser) add(m firewall.Match) { p.rule.Exprs = append(p.rule.Exprs, m) }

func (p *ruleParser) value(opt string) (string, error) {
	if p.i >= len(p.args) {
		return "", fmt.Errorf("%s needs a value", opt)
	}
	v := p.args[p.i]
	p.i++
	return v, nil
}

// skipValues consumes an unknown option's values: everything up to the next option.
func (p *ruleParser) skipValues() {
	for p.i < len(p.args) && !strings.HasPrefix(p.args[p.i], "-") && p.args[p.i] != "!" {
		p.i++
	}
}

func (p *ruleParser) moduleOption(opt string, neg bool) error {
	unknown := func() error {
		p.skipValues()
		p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: p.module + " " + opt})
		return nil
	}
	if !knownModules[p.module] {
		// The module was already marked unknown (or never-matching); its options carry no
		// more information.
		p.skipValues()
		return nil
	}
	switch opt {
	case "--dport", "--destination-port", "--sport", "--source-port":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		r, err := portRanges(v, ":")
		if err != nil {
			return err
		}
		field := firewall.FieldDPort
		if opt == "--sport" || opt == "--source-port" {
			field = firewall.FieldSPort
		}
		p.add(firewall.Match{Field: field, Op: op(neg), Proto: p.l4(), Ports: r})
	case "--dports", "--destination-ports", "--sports", "--source-ports", "--ports":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		r, err := portRanges(v, ":")
		if err != nil {
			return err
		}
		switch opt {
		case "--dports", "--destination-ports":
			p.add(firewall.Match{Field: firewall.FieldDPort, Op: op(neg), Proto: p.l4(), Ports: r})
		case "--ports":
			p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "multiport --ports"})
		default:
			p.add(firewall.Match{Field: firewall.FieldSPort, Op: op(neg), Proto: p.l4(), Ports: r})
		}
	case "--ctstate", "--state":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		p.add(firewall.Match{Field: firewall.FieldCtState, Op: op(neg), Names: lowerList(v)})
	case "--ctstatus":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		names := lowerList(v)
		for _, n := range names {
			if n != "dnat" && n != "snat" {
				p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "conntrack --ctstatus " + v})
				return nil
			}
		}
		p.add(firewall.Match{Field: firewall.FieldCtState, Op: op(neg), Names: names})
	case "--dst-type":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		p.add(firewall.Match{Field: firewall.FieldDAddrType, Op: op(neg), Names: lowerList(v)})
	case "--src-type":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		// An outside source is a unicast address that is not the host's.
		types := lowerList(v)
		known := true
		match := false
		for _, t := range types {
			switch t {
			case "unicast":
				match = true
			case "local", "multicast", "broadcast", "anycast", "blackhole", "unreachable", "prohibit":
			default:
				known = false
			}
		}
		if !known {
			p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "addrtype --src-type " + v})
		} else if match == neg {
			p.add(never())
		}
	case "--mark":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		mark, mask, err := markMask(v)
		if err != nil {
			return err
		}
		p.add(firewall.Match{Field: firewall.FieldMark, Op: op(neg), Mark: mark, Mask: mask})
	case "--comment", "--nfacct-name":
		_, err := p.value(opt)
		return err
	case "--dst-range", "--src-range":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		lo, hi, ok := strings.Cut(v, "-")
		a, err1 := netip.ParseAddr(lo)
		b, err2 := netip.ParseAddr(hi)
		if !ok || err1 != nil || err2 != nil {
			return fmt.Errorf("bad address range %q", v)
		}
		field := firewall.FieldDAddr
		if opt == "--src-range" {
			field = firewall.FieldSAddr
		}
		p.add(firewall.Match{Field: field, Op: op(neg), Family: p.fam, Ranges: []firewall.AddrRange{{Lo: a.Unmap(), Hi: b.Unmap()}}})
	case "--pkt-type":
		v, err := p.value(opt)
		if err != nil {
			return err
		}
		if (strings.ToLower(v) == "unicast") == neg {
			p.add(never())
		}
	case "--syn":
		// The first packet of a new TCP connection is a SYN.
		if neg {
			p.add(never())
		}
	case "--icmp-type", "--icmpv6-type":
		_, err := p.value(opt)
		return err
	case "--tcp-flags":
		mask, err := p.value(opt)
		if err != nil {
			return err
		}
		comp, err := p.value(opt)
		if err != nil {
			return err
		}
		m, ok1 := tcpFlags(mask)
		c, ok2 := tcpFlags(comp)
		if !ok1 || !ok2 {
			return fmt.Errorf("bad --tcp-flags %s %s", mask, comp)
		}
		p.add(firewall.Match{Field: firewall.FieldTCPFlags, Op: op(neg), Proto: "tcp", Mask: m, Mark: c})
	default:
		return p.statefulOption(opt, neg, unknown)
	}
	return nil
}

// statefulOption decides the per-source state modules for one outside source sending
// the first packet of a new connection: it has no recent-list entry, no other
// connection, is under every rate, and is in no source set.
func (p *ruleParser) statefulOption(opt string, neg bool, unknown func() error) error {
	matches := func(m bool) {
		if m == neg {
			p.add(never())
		}
	}
	valueOf := func() error { _, err := p.value(opt); return err }
	switch p.module {
	case "recent":
		// Decided in flushRecent, once every option is known (--rdest may follow).
		switch opt {
		case "--set", "--remove", "--rcheck", "--update":
			p.recent = &recentMatch{action: opt, neg: neg}
		case "--rdest":
			if p.recent == nil {
				p.recent = &recentMatch{}
			}
			p.recent.rdest = true
		case "--rsource", "--reap", "--rttl":
		case "--name", "--seconds", "--hitcount", "--mask":
			return valueOf()
		default:
			return unknown()
		}
	case "limit":
		switch opt {
		case "--limit", "--limit-burst":
			return valueOf()
		default:
			return unknown()
		}
	case "hashlimit":
		switch opt {
		case "--hashlimit-upto", "--hashlimit":
			if err := valueOf(); err != nil {
				return err
			}
			matches(true)
			if !neg {
				p.add(firewall.Match{Field: firewall.FieldAlways, Note: "rate-limited"})
			}
		case "--hashlimit-above":
			if err := valueOf(); err != nil {
				return err
			}
			matches(false)
		case "--hashlimit-burst", "--hashlimit-mode", "--hashlimit-name", "--hashlimit-srcmask",
			"--hashlimit-dstmask", "--hashlimit-htable-size", "--hashlimit-htable-max",
			"--hashlimit-htable-expire", "--hashlimit-htable-gcinterval":
			return valueOf()
		default:
			return unknown()
		}
	case "connlimit":
		switch opt {
		case "--connlimit-above", "--connlimit-upto":
			v, err := p.value(opt)
			if err != nil {
				return err
			}
			n, err := strconv.Atoi(v)
			if err != nil {
				return fmt.Errorf("bad %s %q", opt, v)
			}
			// This connection is the source's only one.
			if opt == "--connlimit-above" {
				matches(1 > n)
			} else {
				matches(1 <= n)
			}
		case "--connlimit-mask":
			return valueOf()
		case "--connlimit-saddr":
		case "--connlimit-daddr":
			p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "connlimit --connlimit-daddr"})
		default:
			return unknown()
		}
	case "set":
		switch opt {
		case "--match-set":
			name, err := p.value(opt)
			if err != nil {
				return err
			}
			flags, err := p.value(opt)
			if err != nil {
				return err
			}
			// Keyed first on the source: an outside source is not in the set.
			if strings.HasPrefix(flags, "src") {
				matches(false)
			} else {
				p.add(firewall.Match{Field: firewall.FieldUnknown, Unknown: "set " + name + " " + flags})
			}
		case "--return-nomatch", "--update-counters", "--update-subcounters":
		default:
			return unknown()
		}
	default:
		return unknown()
	}
	return nil
}

var tcpFlagNames = map[string]uint32{
	"FIN": firewall.TCPFin, "SYN": firewall.TCPSyn, "RST": firewall.TCPRst, "PSH": firewall.TCPPsh,
	"ACK": firewall.TCPAck, "URG": firewall.TCPUrg, "ALL": 0x3f, "NONE": 0,
}

func tcpFlags(v string) (uint32, bool) {
	var bits uint32
	for _, name := range strings.Split(v, ",") {
		b, ok := tcpFlagNames[strings.ToUpper(name)]
		if !ok {
			return 0, false
		}
		bits |= b
	}
	return bits, true
}

// l4 is the transport protocol port options apply to: -p, else the module name.
func (p *ruleParser) l4() string {
	switch p.proto {
	case "tcp", "udp", "6", "17":
		return protoName(p.proto)
	}
	switch p.module {
	case "tcp", "udp":
		return p.module
	}
	return ""
}

func protoName(s string) string {
	switch s {
	case "6":
		return "tcp"
	case "17":
		return "udp"
	case "1":
		return "icmp"
	case "58", "icmpv6", "ipv6-icmp":
		return "ipv6-icmp"
	}
	return s
}

func lowerList(v string) []string { return strings.Split(strings.ToLower(v), ",") }

func (p *ruleParser) target(name string, isGoto bool) ([]firewall.Expr, error) {
	if isGoto {
		return []firewall.Expr{firewall.Verdict{Kind: firewall.VerdictGoto, Target: name}}, nil
	}
	if _, ok := p.chains[name]; ok {
		return []firewall.Expr{firewall.Verdict{Kind: firewall.VerdictJump, Target: name}}, nil
	}
	switch name {
	case "ACCEPT":
		return []firewall.Expr{firewall.Verdict{Kind: firewall.VerdictAccept}}, nil
	case "DROP", "REJECT":
		p.skipTargetOptions()
		return []firewall.Expr{firewall.Verdict{Kind: firewall.VerdictDrop}}, nil
	case "RETURN":
		return []firewall.Expr{firewall.Verdict{Kind: firewall.VerdictReturn}}, nil
	case "QUEUE", "NFQUEUE", "TPROXY":
		p.skipTargetOptions()
		return []firewall.Expr{firewall.Verdict{Kind: firewall.VerdictQueue}}, nil
	case "DNAT", "REDIRECT":
		n, err := p.natTarget(name)
		return []firewall.Expr{n}, err
	case "MARK":
		m, err := p.markTarget()
		return []firewall.Expr{m}, err
	case "CONNMARK":
		restore := p.hasTargetOption("--restore-mark")
		p.skipTargetOptions()
		if restore {
			return []firewall.Expr{firewall.Mark{Unknown: true}}, nil
		}
		return nil, nil
	}
	// An extension target (LOG, MASQUERADE, SNAT, CT, TCPMSS, …): no verdict.
	p.skipTargetOptions()
	return nil, nil
}

// Target options are the "--x value" pairs after -j; they run to the end of the rule
// unless a core option follows.
func (p *ruleParser) targetOptions() map[string]string {
	opts := map[string]string{}
	for p.i < len(p.args) && strings.HasPrefix(p.args[p.i], "--") {
		k := p.args[p.i]
		p.i++
		v := ""
		if p.i < len(p.args) && !strings.HasPrefix(p.args[p.i], "-") {
			v = p.args[p.i]
			p.i++
		}
		opts[k] = v
	}
	return opts
}

func (p *ruleParser) skipTargetOptions() { p.targetOptions() }

func (p *ruleParser) hasTargetOption(name string) bool {
	for _, a := range p.args[p.i:] {
		if a == name {
			return true
		}
	}
	return false
}

func (p *ruleParser) natTarget(name string) (firewall.NAT, error) {
	opts := p.targetOptions()
	if name == "REDIRECT" {
		n := firewall.NAT{Kind: firewall.NATRedirect}
		if v, ok := opts["--to-ports"]; ok {
			r, err := portRanges(v, "-")
			if err != nil || len(r) != 1 || r[0].Lo != r[0].Hi {
				return firewall.NAT{Kind: firewall.NATRedirect, Unknown: "REDIRECT --to-ports " + v}, nil
			}
			n.Port = r[0].Lo
		}
		return n, nil
	}
	v, ok := opts["--to-destination"]
	if !ok {
		return firewall.NAT{Kind: firewall.NATDnat, Unknown: "DNAT without --to-destination"}, nil
	}
	addr, port, err := natDestination(v)
	if err != nil {
		return firewall.NAT{Kind: firewall.NATDnat, Unknown: "DNAT --to-destination " + v}, nil
	}
	return firewall.NAT{Kind: firewall.NATDnat, Addr: addr, Port: port}, nil
}

// natDestination parses "a.b.c.d", "a.b.c.d:port", "[v6]:port" or "v6"; address and
// port ranges are not followed.
func natDestination(v string) (netip.Addr, uint16, error) {
	if ap, err := netip.ParseAddrPort(v); err == nil {
		return ap.Addr().Unmap(), ap.Port(), nil
	}
	if a, err := netip.ParseAddr(strings.Trim(v, "[]")); err == nil {
		return a.Unmap(), 0, nil
	}
	return netip.Addr{}, 0, fmt.Errorf("unsupported destination %q", v)
}

func (p *ruleParser) markTarget() (firewall.Mark, error) {
	opts := p.targetOptions()
	for k, v := range opts {
		value, mask, err := markMask(v)
		if err != nil {
			return firewall.Mark{Unknown: true}, nil
		}
		switch k {
		case "--set-xmark":
			return firewall.Mark{Clear: mask, Xor: value}, nil
		case "--set-mark":
			return firewall.Mark{Clear: mask, Xor: value & mask}, nil
		case "--or-mark":
			return firewall.Mark{Clear: value, Xor: value}, nil
		case "--and-mark":
			return firewall.Mark{Clear: ^value}, nil
		case "--xor-mark":
			return firewall.Mark{Xor: value}, nil
		}
	}
	return firewall.Mark{Unknown: true}, nil
}

// markMask parses "value[/mask]" (hex or decimal); the mask defaults to all ones.
func markMask(v string) (uint32, uint32, error) {
	val, mask, hasMask := strings.Cut(v, "/")
	n, err := strconv.ParseUint(val, 0, 32)
	if err != nil {
		return 0, 0, fmt.Errorf("bad mark %q", v)
	}
	m := uint64(math.MaxUint32)
	if hasMask {
		if m, err = strconv.ParseUint(mask, 0, 32); err != nil {
			return 0, 0, fmt.Errorf("bad mark mask %q", v)
		}
	}
	return uint32(n), uint32(m), nil
}

// portRanges parses "80", "80:90" and comma lists of either (sep is the range separator).
func portRanges(v, sep string) ([]firewall.PortRange, error) {
	var out []firewall.PortRange
	for _, part := range strings.Split(v, ",") {
		lo, hi, isRange := strings.Cut(part, sep)
		a, err := parsePort(lo, 0)
		if err != nil {
			return nil, err
		}
		b := a
		if isRange {
			if b, err = parsePort(hi, math.MaxUint16); err != nil {
				return nil, err
			}
		}
		out = append(out, firewall.PortRange{Lo: a, Hi: b})
	}
	return out, nil
}

func parsePort(s string, empty uint16) (uint16, error) {
	if s == "" {
		return empty, nil
	}
	n, err := strconv.ParseUint(s, 10, 16)
	if err != nil {
		return 0, fmt.Errorf("bad port %q", s)
	}
	return uint16(n), nil
}

// prefixes parses "-s/-d" values: comma-separated addresses with optional /len or
// dotted /mask.
func prefixes(v string) ([]netip.Prefix, error) {
	var out []netip.Prefix
	for _, part := range strings.Split(v, ",") {
		if pfx, err := netip.ParsePrefix(part); err == nil {
			out = append(out, pfx.Masked())
			continue
		}
		addr, mask, hasMask := strings.Cut(part, "/")
		a, err := netip.ParseAddr(addr)
		if err != nil {
			return nil, fmt.Errorf("bad address %q", part)
		}
		if !hasMask {
			out = append(out, netip.PrefixFrom(a, a.BitLen()))
			continue
		}
		m, err := netip.ParseAddr(mask)
		if err != nil {
			return nil, fmt.Errorf("bad mask %q", part)
		}
		bits := 0
		for _, b := range m.AsSlice() {
			for i := 7; i >= 0 && b&(1<<i) != 0; i-- {
				bits++
			}
		}
		pfx, err := a.Prefix(bits)
		if err != nil {
			return nil, err
		}
		out = append(out, pfx)
	}
	return out, nil
}
